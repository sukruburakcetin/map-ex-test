import { nativeCoverageOffsetMeters } from './nativeCoverageAlignment';

export type HighlightTile = [number, number, number];
interface TileFeature {
  properties: Record<string, any>;
  extent: number;
  loadGeometry(): { x: number; y: number }[][];
}
interface TileSource { length: number; feature(i: number): TileFeature }
export interface TileHighlightHost {
  native?: (role: 'selected' | 'hover', id: string | null) => void;
  tiles(): HighlightTile[];
  zoom(): number;
  styles: any[];
  load(tile: HighlightTile, signal: AbortSignal): Promise<ArrayBuffer>;
  decode(buffer: ArrayBuffer): { layers: Record<string, TileSource> };
  create(properties: any): any;
  replace(role: 'selected' | 'hover', graphics: any[]): void;
  dispose(): void;
  warn(error: unknown): void;
}
interface Shape { key: string; source: string; properties: Record<string, any>; geometry: any; vertices: number }

/** Classic filters generated by turboTileStyle. Unknown operators fail closed. */
export function matchesTileFilter(filter: any, props: Record<string, any>): boolean {
  if (!filter) return true;
  const [op, key, ...values] = filter;
  if (op === 'all') return filter.slice(1).every((f: any) => matchesTileFilter(f, props));
  if (op === 'any') return filter.slice(1).some((f: any) => matchesTileFilter(f, props));
  if (op === 'has') return props[key] !== undefined;
  if (op === '!has') return props[key] === undefined;
  const value = props[key], target = values[0];
  switch (op) {
    case '==': return value === target;
    case '!=': return value !== target;
    case 'in': return values.includes(value);
    case '!in': return !values.includes(value);
    case '>=': return value >= target;
    case '>': return value > target;
    case '<=': return value <= target;
    case '<': return value < target;
    default: return false;
  }
}

/** Persistent graphics only; selection never edits, replaces or reloads coverage tiles.
 * Cache only requested sequence geometry, bounded by tile entries and vertex count.
 */
export class TileSequenceHighlights {
  private host: TileHighlightHost | null = null;
  private selected: string | null = null;
  private hovered: string | null = null;
  private pending: AbortController | null = null;
  private signature = '';
  private cache = new Map<string, Shape[]>();
  private vertices = 0;
  private graphics = new Map<string, any>();

  bind(host: TileHighlightHost): void { this.detach(); this.host = host; }
  select(id: string | null): Promise<void> { if (id !== this.selected) this.host?.replace('selected', []); this.selected = id; return this.refresh(); }
  hover(id: string | null): Promise<void> { if (id !== this.hovered) this.host?.replace('hover', []); this.hovered = id; return this.refresh(); }
  cancelPending(): void { this.pending?.abort(); this.pending = null; this.signature = ''; }
  detach(): void {
    this.cancelPending(); this.host?.dispose(); this.host = null;
    this.selected = this.hovered = null; this.cache.clear(); this.vertices = 0; this.graphics.clear();
  }

  async refresh(): Promise<void> {
    const host = this.host;
    if (!host) return;
    const selected = this.selected, hovered = this.hovered, zoom = host.zoom();
    if (host.native) {
      const signature = JSON.stringify([selected, hovered]);
      if (signature === this.signature) return;
      this.signature = signature;
      try { host.native('selected', selected); host.native('hover', hovered); }
      catch (error) { this.signature = ''; host.warn(error); }
      return;
    }
    const tiles = selected || hovered ? host.tiles() : [];
    const signature = JSON.stringify([selected, hovered, zoom, tiles]);
    if (signature === this.signature) return;
    this.cancelPending(); this.signature = signature;
    // Hide a changed target immediately; never leave the previous sequence highlighted.
    if (!selected) host.replace('selected', []);
    if (!hovered) host.replace('hover', []);
    const controller = new AbortController(); this.pending = controller;
    const signal = controller.signal;
    const current = () => !signal.aborted && this.host === host;
    const previousGraphics = this.graphics;
    const next = { selected: [] as any[], hover: [] as any[] }, used = new Map<string, any>();
    let shownSelected = -1, shownHover = -1;
    const commit = () => {
      if (!current() || (shownSelected === next.selected.length && shownHover === next.hover.length)) return;
      host.replace('selected', next.selected); host.replace('hover', next.hover);
      shownSelected = next.selected.length; shownHover = next.hover.length;
      this.graphics = new Map(used);
    };
    try {
      const ids = [...new Set([selected, hovered].filter((id): id is string => !!id))];
      for (const tile of tiles) {
        const missing = ids.filter(id => !this.cache.has(`${tile.join('/')}:${id}`));
        let decoded = new Map<string, Shape[]>();
        if (missing.length) {
          const buffer = await host.load(tile, signal);
          if (!current()) return;
          const shapes = decoded = await this.extract(host, buffer, tile, missing, signal);
          if (!current()) return;
          for (const id of missing) this.store(`${tile.join('/')}:${id}`, shapes.get(id) || []);
        }
        for (const id of ids) {
          const cacheKey = `${tile.join('/')}:${id}`;
          const shapes = decoded.get(id) || this.cache.get(cacheKey) || [];
          if (this.cache.has(cacheKey)) { this.cache.delete(cacheKey); this.cache.set(cacheKey, shapes); }
          for (const shape of shapes) {
            for (const role of ['selected', 'hover'] as const) {
              if (id !== (role === 'selected' ? selected : hovered) || (role === 'hover' && shape.source !== 'sequence')) continue;
              const applicable = host.styles.filter(style => style['source-layer'] === shape.source && zoom >= (style.minzoom ?? 0)
                && zoom < (style.maxzoom ?? Infinity) && matchesTileFilter(style.filter, shape.properties));
              const styles = role === 'hover' ? (applicable.length ? [{ id: 'hover', type: 'line', paint: { 'line-width': 6, 'line-opacity': 1 } }] : []) : applicable;
              for (const style of styles) {
                const key = `${role}:${shape.key}:${style.id}`;
                const graphic = previousGraphics.get(key) || host.create({ geometry: shape.geometry,
                  symbol: this.symbol(style, role), attributes: { sequenceId: id, tileSequenceHighlight: true } });
                used.set(key, graphic); next[role].push(graphic);
              }
            }
          }
        }
        // Cached pointer tiles appear first; extending the visible route never gates on every network tile.
        if (next.selected.length || next.hover.length) commit();
      }
      if (!current()) return;
      commit();
    } catch (error) {
      if (current()) { this.signature = ''; host.warn(error); }
    } finally { if (this.pending === controller) this.pending = null; }
  }

  private symbol(style: any, role: 'selected' | 'hover'): any {
    const paint = style.paint || {}, color = role === 'hover' ? [0, 255, 136] : [0, 0, 255];
    // Mapbox dimensions are CSS pixels; ArcGIS simple-symbol numeric sizes are points.
    if (style.type === 'line') return { type: 'simple-line', color: [...color, paint['line-opacity'] ?? 1],
      width: (paint['line-width'] ?? 1) * 0.75, cap: 'butt', join: 'miter' };
    const stroke = paint['circle-stroke-width'] ?? 0;
    return { type: 'simple-marker', style: 'circle', size: 2 * (paint['circle-radius'] ?? 5) * 0.75,
      color: [...color, paint['circle-opacity'] ?? 1], outline: { color: paint['circle-stroke-color'] ?? '#000000', width: stroke * 0.75 } };
  }

  private store(key: string, shapes: Shape[]): void {
    const count = shapes.reduce((sum, shape) => sum + shape.vertices, 0);
    // A large sequence is rendered but not retained in the geometry cache.
    if (count > 100000) return;
    while (this.cache.size && (this.cache.size >= 64 || this.vertices + count > 100000)) {
      const oldest = this.cache.keys().next().value!;
      this.vertices -= this.cache.get(oldest)!.reduce((sum, shape) => sum + shape.vertices, 0);
      this.cache.delete(oldest);
    }
    this.cache.set(key, shapes); this.vertices += count;
  }

  private async extract(host: TileHighlightHost, buffer: ArrayBuffer, tile: HighlightTile, ids: string[], signal: AbortSignal): Promise<Map<string, Shape[]>> {
    const result = new Map(ids.map(id => [id, [] as Shape[]]));
    if (!buffer.byteLength) return result;
    const layers = host.decode(buffer).layers;
    const [x, y, z] = tile, world = 2 * Math.PI * 6378137, span = world / 2 ** z;
    const offset = nativeCoverageOffsetMeters(z);
    let deadline = performance.now() + 4;
    for (const name of ['sequence', 'image']) {
      const layer = layers[name]; if (!layer || (name === 'image' && z < 14)) continue;
      for (let i = 0; i < layer.length; i++) {
        if ((i & 127) === 0) {
          if (signal.aborted) throw new DOMException('Cancelled', 'AbortError');
          if (performance.now() >= deadline) { await new Promise(resolve => setTimeout(resolve, 0)); deadline = performance.now() + 4; }
        }
        const feature = layer.feature(i), props = feature.properties;
        const id = String(props[name === 'sequence' ? 'id' : 'sequence_id'] ?? '');
        const output = result.get(id); if (!output) continue;
        const paths = feature.loadGeometry(), extent = feature.extent || 4096;
        const project = (p: { x: number; y: number }) => [(x + p.x / extent) * span - world / 2 + offset,
          world / 2 - (y + p.y / extent) * span - offset];
        if (name === 'image') {
          const p = paths[0]?.[0];
          // MVT buffers repeat adjacent points. Keep only the canonical tile's copy.
          if (!p || p.x < 0 || p.y < 0 || p.x >= extent || p.y >= extent) continue;
          const [px, py] = project(p);
          output.push({ key: `${tile.join('/')}:${name}:${i}`, source: name, properties: props, vertices: 1,
            geometry: { type: 'point', x: px, y: py, spatialReference: { wkid: 3857 } } });
        } else {
          // Clip buffered lines to tile bounds to avoid dark seams from duplicate segments.
          const clipped = paths.flatMap(path => clipTilePath(path, extent));
          if (!clipped.length) continue;
          output.push({ key: `${tile.join('/')}:${name}:${i}`, source: name, properties: props,
            vertices: clipped.reduce((n, path) => n + path.length, 0),
            geometry: { type: 'polyline', paths: clipped.map(path => path.map(project)), spatialReference: { wkid: 3857 } } });
        }
      }
    }
    return result;
  }
}

/** Liang–Barsky clipping preserves original vertices; it never joins separate tile paths. */
export function clipTilePath(path: { x: number; y: number }[], extent: number): { x: number; y: number }[][] {
  const paths: { x: number; y: number }[][] = [];
  for (let i = 1; i < path.length; i++) {
    const a = path[i - 1], b = path[i], dx = b.x - a.x, dy = b.y - a.y;
    let lo = 0, hi = 1, keep = true;
    const p = [-dx, dx, -dy, dy], q = [a.x, extent - a.x, a.y, extent - a.y];
    for (let j = 0; j < 4; j++) {
      if (p[j] === 0) { if (q[j] < 0) keep = false; }
      else { const t = q[j] / p[j]; if (p[j] < 0) lo = Math.max(lo, t); else hi = Math.min(hi, t); }
    }
    if (!keep || lo > hi) continue;
    const start = { x: a.x + lo * dx, y: a.y + lo * dy }, end = { x: a.x + hi * dx, y: a.y + hi * dy };
    const last = paths[paths.length - 1], tail = last?.[last.length - 1];
    if (tail && tail.x === start.x && tail.y === start.y) last.push(end); else paths.push([start, end]);
  }
  return paths;
}
